"""Transcript model and HTML rendering for the session log viewer.

``TranscriptBuilder`` reduces canonical events (persisted, plus live-only
``text_delta``) into a node tree that the ``viewer/_nodes.html`` macros render.
For live updates, :meth:`TranscriptBuilder.apply` returns the :class:`Change`
records an event caused, so the SSE endpoint can send one fragment per change.

Event handling follows ``cli/src/archie_cli/tui/app.py`` (``_render_canonical``
and ``_handle_scoped_event``): child events (non-null ``scope`` and
``subagent_index``) belong to the ``task`` tool call whose ``tool_use_id`` is
their scope; assistant text is keyed by request identity so streamed deltas and
the final ``assistant_message`` reconcile.
"""

