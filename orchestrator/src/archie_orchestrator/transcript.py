PREVIEW_CHARS = 8000

# ---------------------------------------------------------------------------
# Markdown
# ---------------------------------------------------------------------------

_FORMATTER = HtmlFormatter(nowrap=True)


def highlight_code(code: str, lang: str = "") -> str:
    """Return ``<pre class="highlight"><code>…</code></pre>`` with Pygments spans."""
    try:
        lexer = get_lexer_by_name(lang) if lang else TextLexer()
    except ClassNotFound:
        lexer = TextLexer()
    body = highlight(code, lexer, _FORMATTER)
    return f'<pre class="highlight"><code>{body}</code></pre>'


def _highlight(code: str, lang: str, _attrs: str) -> str:
    return highlight_code(code, lang.split()[0] if lang else "") + "\n"


def _cell_open(renderer, tokens, idx, options, env):
    token = tokens[idx]
    style = token.attrGet("style")
    if style:
        token.attrs.pop("style", None)
        match = re.fullmatch(r"text-align:(left|right|center)", style)
        if match:
            token.attrSet("class", f"align-{match.group(1)}")
    return renderer.renderToken(tokens, idx, options, env)


def _image(renderer, tokens, idx, options, env):
    token = tokens[idx]
    src = html.escape(token.attrGet("src") or "", quote=True)
    alt = html.escape(renderer.renderInlineAsText(token.children or [], options, env))
    return f'<a class="image-link" href="{src}" rel="noreferrer">image: {alt or src}</a>'


_MD = MarkdownIt("js-default", {"highlight": _highlight})
_MD.add_render_rule("th_open", _cell_open)
_MD.add_render_rule("td_open", _cell_open)
_MD.add_render_rule("image", _image)


def render_markdown(text: str) -> Markup:
    """Render untrusted Markdown: raw HTML escaped, unsafe links dropped, no images."""
    return Markup(_MD.render(text))


def pygments_css() -> str:
    """CSS for ``.highlight`` code: light ``friendly``, dark ``github-dark``."""
    light = HtmlFormatter(style="friendly").get_style_defs(".highlight")
    dark = HtmlFormatter(style="github-dark").get_style_defs(".highlight")
    dark = "\n".join("    " + line for line in dark.splitlines())
    return (
        "/* Generated by: python -m archie_orchestrator.transcript --pygments-css */\n"
        f"{light}\n@media (prefers-color-scheme: dark) {{\n{dark}\n}}\n"
    )


# ---------------------------------------------------------------------------
# Rich-style tool summary markup (subset emitted by archie_shared.tool_summaries)
# ---------------------------------------------------------------------------

_STYLE_CLASSES = {
    "bold": "b",
    "dim": "dim",
    "italic": "i",
    "red": "err",
    "#ff6d67": "err",
    "#67c26d": "ok",
    "#676767": "default",
}
_MARKUP_TOKEN = re.compile(r"\\\[|\\\]|\[/[^\]]*\]|\[[^\]\[]+\]")


def markup_to_html(markup: str) -> Markup:
    """Convert Rich-style summary markup to escaped HTML spans."""
    out: list[str] = []
    depth = 0
    pos = 0
    for match in _MARKUP_TOKEN.finditer(markup):
        out.append(html.escape(markup[pos : match.start()]))
        token = match.group(0)
        if token in ("\\[", "\\]"):
            out.append(token[1])
        elif token.startswith("[/"):
            if depth:
                out.append("</span>")
                depth -= 1
        else:
            styles = token[1:-1].lower().split()
            classes = [_STYLE_CLASSES[s] for s in styles if s in _STYLE_CLASSES]
            out.append(f'<span class="{" ".join(classes)}">' if classes else "<span>")
            depth += 1
        pos = match.end()
    out.append(html.escape(markup[pos:]))
    out.append("</span>" * depth)
    return Markup("".join(out))


# ---------------------------------------------------------------------------
# Nodes
# ---------------------------------------------------------------------------

_ID_UNSAFE = re.compile(r"[^A-Za-z0-9_-]")


def dom_id(*parts: object) -> str:
    """Join parts into an HTML id, replacing characters outside [A-Za-z0-9_-]."""
    return "-".join(_ID_UNSAFE.sub("_", str(p)) for p in parts if p is not None)


def preview(text: str) -> tuple[str, int]:
    """Return (text capped at PREVIEW_CHARS, characters omitted)."""
    if len(text) <= PREVIEW_CHARS:
        return text, 0
    return text[:PREVIEW_CHARS], len(text) - PREVIEW_CHARS


@dataclass
class TextNode:
    id: str
    role: Literal["user", "assistant"]
    content: str
    interrupted: bool = False
    kind: str = "text"

    @property
    def html(self) -> Markup:
        return render_markdown(self.content)


@dataclass
class StreamNode:
    id: str
    text: str = ""
    kind: str = "stream"


@dataclass
class NoticeNode:
    id: str
    variant: Literal["compaction", "turn-error", "turn-interrupted"]
    title: str
    detail: str = ""
    body_markdown: str = ""
    kind: str = "notice"

    @property
    def body_html(self) -> Markup:
        return render_markdown(self.body_markdown) if self.body_markdown else Markup("")


@dataclass
class SubagentNode:
    id: str
    scope: str
    index: int
    items: list = field(default_factory=list)
    kind: str = "subagent"

    @property
    def items_id(self) -> str:
        return f"{self.id}-items"


@dataclass
class ToolNode:
    id: str
    tool_use_id: str
    name: str
    input: dict
    status: Literal["pending", "ok", "error"] = "pending"
    result: str | None = None
    duration_ms: int = 0
    children: list[SubagentNode] = field(default_factory=list)
    kind: str = "tool"

    @property
    def children_id(self) -> str:
        return f"{self.id}-children"

    @property
    def summary_html(self) -> Markup:
        if self.result is None:
            if self.name == "exec":
                return markup_to_html(format_tool_activity(self.name, self.input))
            return markup_to_html(format_tool_pending(self.name, self.input))
        summary = format_tool_complete(
            self.name, self.input, self.result, self.status == "error", self.duration_ms
        )
        # Multi-line summaries (diffs, error output) show their first line here.
        return markup_to_html(summary.split("\n", 1)[0])

    @property
    def detail_html(self) -> Markup:
        """Lines after the first of the completed summary (diff or error output)."""
        if self.result is None:
            return Markup("")
        summary = format_tool_complete(
            self.name, self.input, self.result, self.status == "error", self.duration_ms
        )
        parts = summary.split("\n", 1)
        return markup_to_html(parts[1]) if len(parts) > 1 else Markup("")

    @property
    def input_html(self) -> Markup:
        if self.name == "exec" and isinstance(self.input.get("source"), str):
            shown, omitted = preview(self.input["source"])
            out = highlight_code(shown, "python")
        else:
            text = json.dumps(self.input, indent=2, ensure_ascii=False, default=str)
            shown, omitted = preview(text)
            out = highlight_code(shown, "json")
        if omitted:
            out += f'<p class="omitted">… {omitted} more characters</p>'
        return Markup(out)

    @property
    def result_preview(self) -> tuple[str, int]:
        return preview(self.result or "")


@dataclass
class TurnNode:
    id: str
    number: int
    user: TextNode | None
    items: list = field(default_factory=list)
    usage: UsageTotals = field(default_factory=UsageTotals)  # root-scope requests only
    stop_reason: str | None = None
    kind: str = "turn"

    @property
    def items_id(self) -> str:
        return f"{self.id}-items"

    @property
    def footer_id(self) -> str:
        return f"{self.id}-footer"


@dataclass
class Change:
    """One DOM update caused by an event.

    - ``append``: add ``node`` at the end of ``parent_id`` (``None`` = transcript root).
    - ``replace``: replace the element ``target_id`` with ``node``.
    - ``append_text``: append ``text`` to the element ``target_id``.
    - ``remove``: delete the element ``target_id`` if present.
    """

    kind: Literal["append", "replace", "append_text", "remove"]
    node: object | None = None
    parent_id: str | None = None
    target_id: str | None = None
    text: str = ""


