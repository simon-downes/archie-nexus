"""HTML rendering helpers for the session log viewer.

The transcript model itself is :mod:`archie_shared.transcript`, shared with the TUI.
This module renders its nodes for the ``viewer/_nodes.html`` macros: Markdown,
Pygments highlighting, Rich-style summary markup and per-node HTML pieces.
"""

from __future__ import annotations

import html
import re
import sys

from archie_shared.transcript import (
    CompactionNode,
    ToolNode,
    tool_detail_sections,
    tool_extra,
    tool_headline,
)
from markdown_it import MarkdownIt
from markupsafe import Markup
from pygments import highlight
from pygments.formatters import HtmlFormatter
from pygments.lexers import TextLexer, get_lexer_by_name, get_lexer_for_filename
from pygments.util import ClassNotFound

# ---------------------------------------------------------------------------
# Markdown
# ---------------------------------------------------------------------------

_FORMATTER = HtmlFormatter(nowrap=True)


def highlight_code(code: str, lang: str = "") -> str:
    """Return ``<pre class="highlight"><code>…</code></pre>`` with Pygments spans."""
    try:
        lexer = get_lexer_by_name(lang) if lang else TextLexer()
    except ClassNotFound:
        lexer = TextLexer()
    body = highlight(code, lexer, _FORMATTER)
    return f'<pre class="highlight"><code>{body}</code></pre>'


def _highlight(code: str, lang: str, _attrs: str) -> str:
    return highlight_code(code, lang.split()[0] if lang else "") + "\n"


def _cell_open(renderer, tokens, idx, options, env):
    token = tokens[idx]
    style = token.attrGet("style")
    if style:
        token.attrs.pop("style", None)
        match = re.fullmatch(r"text-align:(left|right|center)", style)
        if match:
            token.attrSet("class", f"align-{match.group(1)}")
    return renderer.renderToken(tokens, idx, options, env)


def _image(renderer, tokens, idx, options, env):
    token = tokens[idx]
    src = html.escape(token.attrGet("src") or "", quote=True)
    alt = html.escape(renderer.renderInlineAsText(token.children or [], options, env))
    return f'<a class="image-link" href="{src}" rel="noreferrer">image: {alt or src}</a>'


_MD = MarkdownIt("js-default", {"highlight": _highlight})
_MD.add_render_rule("th_open", _cell_open)
_MD.add_render_rule("td_open", _cell_open)
_MD.add_render_rule("image", _image)


def render_markdown(text: str) -> Markup:
    """Render untrusted Markdown: raw HTML escaped, unsafe links dropped, no images."""
    return Markup(_MD.render(text))


def pygments_css() -> str:
    """CSS for ``.highlight`` code: light ``friendly``, dark ``github-dark``."""
    light = HtmlFormatter(style="friendly").get_style_defs(".highlight")
    dark = HtmlFormatter(style="github-dark").get_style_defs(".highlight")
    dark = "\n".join("    " + line for line in dark.splitlines())
    return (
        "/* Generated by: python -m archie_orchestrator.transcript --pygments-css */\n"
        f"{light}\n@media (prefers-color-scheme: dark) {{\n{dark}\n}}\n"
    )


# ---------------------------------------------------------------------------
# Rich-style tool summary markup (subset emitted by archie_shared.tool_summaries)
# ---------------------------------------------------------------------------

_STYLE_CLASSES = {
    "bold": "b",
    "dim": "dim",
    "italic": "i",
    "red": "err",
    "#ff6d67": "err",
    "#67c26d": "ok",
    "#676767": "default",
}
_MARKUP_TOKEN = re.compile(r"\\\[|\\\]|\[/[^\]]*\]|\[[^\]\[]+\]")


def markup_to_html(markup: str) -> Markup:
    """Convert Rich-style summary markup to escaped HTML spans."""
    out: list[str] = []
    depth = 0
    pos = 0
    for match in _MARKUP_TOKEN.finditer(markup):
        out.append(html.escape(markup[pos : match.start()]))
        token = match.group(0)
        if token in ("\\[", "\\]"):
            out.append(token[1])
        elif token.startswith("[/"):
            if depth:
                out.append("</span>")
                depth -= 1
        else:
            styles = token[1:-1].lower().split()
            classes = [_STYLE_CLASSES[s] for s in styles if s in _STYLE_CLASSES]
            out.append(f'<span class="{" ".join(classes)}">' if classes else "<span>")
            depth += 1
        pos = match.end()
    out.append(html.escape(markup[pos:]))
    out.append("</span>" * depth)
    return Markup("".join(out))


# ---------------------------------------------------------------------------
# Node rendering helpers (registered as Jinja globals by ``web.py``)
# ---------------------------------------------------------------------------


def tool_summary_html(tool: ToolNode) -> Markup:
    """The tool row's one-line summary."""
    return markup_to_html(tool_headline(tool))


def tool_extra_html(tool: ToolNode) -> Markup:
    """Lines under the summary: a diff or condensed error output."""
    extra = tool_extra(tool)
    return markup_to_html(extra) if extra else Markup("")


def tool_sections_html(tool: ToolNode) -> list[dict]:
    """Highlighted input/result blocks for the tool detail overlay."""
    out = []
    for section in tool_detail_sections(tool):
        language = section.language
        if language is None and section.filename:
            try:
                language = get_lexer_for_filename(section.filename).aliases[0]
            except ClassNotFound:
                language = None
        if language:
            body = highlight_code(section.text, language)
        else:
            body = f'<pre class="plain"><code>{html.escape(section.text)}</code></pre>'
        out.append({"title": section.title, "html": Markup(body), "omitted": section.omitted})
    return out


def compaction_text(node: CompactionNode) -> tuple[str, str]:
    """(title, detail) for a compaction row."""
    reason = _compaction_reason(node.reason)
    if node.marker:
        return (
            f"Context compacted ({reason})",
            f"{node.tokens_before:,} → {(node.tokens_after or 0):,} tokens",
        )
    if node.status == "pending":
        return f"Compacting ({reason})", f"{node.tokens_before:,} tokens"
    if node.status == "success":
        after = f"{node.tokens_after:,}" if node.tokens_after is not None else "?"
        return f"Compaction success ({reason})", f"{node.tokens_before:,} → {after} tokens"
    return f"Compaction {node.status} ({reason})", node.error or f"Compaction {node.status}"


def _compaction_reason(reason: str) -> str:
    return {"threshold": "threshold", "cold_cache": "cold cache", "manual": "manual"}.get(
        reason, reason
    )


if __name__ == "__main__":
    if sys.argv[1:] == ["--pygments-css"]:
        sys.stdout.write(pygments_css())
    else:
        sys.exit("usage: python -m archie_orchestrator.transcript --pygments-css")
