# Builder
# ---------------------------------------------------------------------------


def _compaction_reason(reason: str) -> str:
    return {"threshold": "threshold", "cold_cache": "cold cache", "manual": "manual"}.get(
        reason, reason
    )


class TranscriptBuilder:
    """Reduce canonical events to transcript nodes, reporting DOM changes per event."""

    def __init__(self) -> None:
        self.turns: list[TurnNode] = []
        self.preamble: list = []  # items before the first user message
        self.usage = UsageTotals()
        self.last_persisted_id: str | None = None
        self._tools: dict[str, ToolNode] = {}
        self._subagents: dict[tuple[str, int], SubagentNode] = {}
        self._streams: dict[tuple, StreamNode] = {}
        self._finalized: set[tuple] = set()
        self._seen: set[str] = set()
        self._new_groups: set[str] = set()  # group ids created by the event being applied

    # -- containers -----------------------------------------------------

    def _current_turn(self) -> TurnNode | None:
        return self.turns[-1] if self.turns else None

    def _root_container(self) -> tuple[list, str | None]:
        turn = self._current_turn()
        if turn is None:
            return self.preamble, None
        return turn.items, turn.items_id

    def _subagent(self, scope: str, index: int, changes: list[Change]) -> SubagentNode:
        """Return the child group for (scope, index), creating it on first use.

        A new group is sent as one ``append`` that is rendered after ``apply``
        returns, so it already holds the items this event adds; callers must not
        also append those items. The group is preceded by a ``remove`` of its id,
        which clears a group left in the page by an earlier live connection.
        """
        key = (scope, index)
        node = self._subagents.get(key)
        if node is not None:
            return node
        node = SubagentNode(id=dom_id("sub", scope, index), scope=scope, index=index)
        self._subagents[key] = node
        parent = self._tools.get(scope)
        if parent is not None:
            parent.children.append(node)
            parent_id = parent.children_id
        else:
            items, parent_id = self._root_container()
            items.append(node)
        changes.append(Change("remove", target_id=node.id))
        changes.append(Change("append", node, parent_id=parent_id))
        self._new_groups.add(node.id)
        return node

    def _container(self, event, changes: list[Change]) -> tuple[list, str | None]:
        """Return (items, DOM id of items) for the event's scope."""
        scope = getattr(event, "scope", None)
        index = getattr(event, "subagent_index", None)
        if scope is not None and index is not None:
            node = self._subagent(scope, index, changes)
            return node.items, node.items_id
        return self._root_container()

    def _add(self, event, node, changes: list[Change]) -> None:
        items, parent_id = self._container(event, changes)
        items.append(node)
        if not self._in_new_group(parent_id):
            changes.append(Change("append", node, parent_id=parent_id))

    def _in_new_group(self, items_id: str | None) -> bool:
        """True when ``items_id`` belongs to a group created by the current event."""
        return items_id is not None and items_id.removesuffix("-items") in self._new_groups

    @staticmethod
    def _request_key(event) -> tuple:
        return (event.scope, event.subagent_index, event.turn, event.iteration, event.request_id)

    def _stream_id(self, key: tuple) -> str:
        scope, index, turn, iteration, request_id = key
        return dom_id("stream", scope, index, turn, iteration, request_id)

    # -- events -----------------------------------------------------------

    def apply(self, event) -> list[Change]:
        """Apply one event and return the DOM changes it caused."""
        event_id = getattr(event, "id", None)
        if event_id is not None:
            if event_id in self._seen:
                return []
            self._seen.add(event_id)
            if event.persist:
                self.last_persisted_id = event_id
        changes: list[Change] = []
        self._new_groups.clear()
        child = getattr(event, "scope", None) is not None and (
            getattr(event, "subagent_index", None) is not None
        )

        if isinstance(event, UserMessage):
            if child:
                if event.content:
                    self._add(
                        event, TextNode(dom_id("msg", event.id), "user", event.content), changes
                    )
            else:
                user = TextNode(dom_id("msg", event.id), "user", event.content)
                turn = TurnNode(id=dom_id("turn", event.id), number=event.turn, user=user)
                self.turns.append(turn)
                changes.append(Change("append", turn))
        elif isinstance(event, TextDelta):
            key = self._request_key(event)
            if key in self._finalized:
                return changes
            stream = self._streams.get(key)
            if stream is None:
                stream = StreamNode(id=self._stream_id(key), text=event.text)
                self._streams[key] = stream
                # A reconnect starts a new builder mid-stream; drop the old partial block.
                changes.append(Change("remove", target_id=stream.id))
                self._add(event, stream, changes)
            else:
                stream.text += event.text
                changes.append(
                    Change("append_text", target_id=f"{stream.id}-text", text=event.text)
                )
        elif isinstance(event, AssistantMessage):
            key = self._request_key(event)
            self._finalized.add(key)
            stream = self._streams.pop(key, None)
            stream_id = self._stream_id(key)
            node = TextNode(dom_id("msg", event.id), "assistant", event.content, event.interrupted)
            visible = bool(event.content) or event.interrupted
            items, _ = self._container(event, changes)
            if stream is not None:
                index = next((i for i, item in enumerate(items) if item is stream), None)
                if visible and index is not None:
                    items[index] = node
                    changes.append(Change("replace", node, target_id=stream_id))
                else:
                    if index is not None:
                        items.pop(index)
                    changes.append(Change("remove", target_id=stream_id))
            elif visible:
                changes.append(Change("remove", target_id=stream_id))
                self._add(event, node, changes)
            else:
                changes.append(Change("remove", target_id=stream_id))
        elif isinstance(event, ToolCall):
            node = ToolNode(
                id=dom_id("tool", event.tool_use_id),
                tool_use_id=event.tool_use_id,
                name=event.name,
                input=dict(event.input),
            )
            self._tools[event.tool_use_id] = node
            self._add(event, node, changes)
        elif isinstance(event, ToolResult):
            node = self._tools.get(event.tool_use_id)
            if node is None:
                node = ToolNode(
                    id=dom_id("tool", event.tool_use_id),
                    tool_use_id=event.tool_use_id,
                    name="tool",
                    input={},
                )
                self._tools[event.tool_use_id] = node
                node.result = event.content
                node.status = "error" if event.is_error else "ok"
                node.duration_ms = event.duration_ms
                self._add(event, node, changes)
            else:
                node.result = event.content
                node.status = "error" if event.is_error else "ok"
                node.duration_ms = event.duration_ms
                changes.append(Change("replace", node, target_id=node.id))
        elif isinstance(event, LLMRequest):
            self.usage.add(event)
            changes.append(Change("replace", self.usage, target_id="session-usage"))
            turn = self._current_turn()
            if not child and turn is not None:
                turn.usage.add(event)
                changes.append(Change("replace", turn, target_id=turn.footer_id))
        elif isinstance(event, ContextCompacted):
            self._add(
                event,
                NoticeNode(
                    id=dom_id("note", event.id),
                    variant="compaction",
                    title=f"Context compacted ({_compaction_reason(event.reason)})",
                    detail=f"{event.tokens_before:,} → {event.tokens_after:,} tokens",
                    body_markdown=event.summary,
                ),
                changes,
            )
        elif isinstance(event, CompactionComplete):
            if event.status == "success":
                after = f"{event.tokens_after:,}" if event.tokens_after is not None else "?"
                detail = f"{event.tokens_before:,} → {after} tokens"
            else:
                detail = event.error or f"Compaction {event.status}"
            self._add(
                event,
                NoticeNode(
                    id=dom_id("note", event.id),
                    variant="compaction",
                    title=f"Compaction {event.status} ({_compaction_reason(event.reason)})",
                    detail=detail,
                    body_markdown=event.summary or "",
                ),
                changes,
            )
        elif isinstance(event, TurnError):
            self._add(
                event,
                NoticeNode(dom_id("note", event.id), "turn-error", "Turn failed", event.message),
                changes,
            )
        elif isinstance(event, TurnInterrupted):
            self._add(
                event,
                NoticeNode(dom_id("note", event.id), "turn-interrupted", "Turn interrupted"),
                changes,
            )
        elif isinstance(event, TurnComplete):
            turn = self._current_turn()
            if not child and turn is not None:
                turn.stop_reason = event.stop_reason
                changes.append(Change("replace", turn, target_id=turn.footer_id))
        # CompactionStart, IterationStart, SessionStarted, and live-only status
        # frames have no transcript representation.
        return changes


def build(events) -> TranscriptBuilder:
    """Build a transcript from a complete event list (full-page rendering)."""
    builder = TranscriptBuilder()
    for event in events:
        builder.apply(event)
    return builder


