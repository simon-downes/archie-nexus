"""Startup hook: write ``~/.aws/config`` from ``plugins.aws.settings``.

Each configured profile becomes a role profile that assumes its ARN with the
base credentials the host projects into the environment. The file holds no
credential values; it is container-local and regenerated at every start.

The hook never overwrites a host file: it refuses when ``~/.aws`` or
``~/.aws/config`` is a mount point, or when an existing ``~/.aws/config`` does
not start with the generated header.
"""

from __future__ import annotations

import os
import re
import tempfile
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from archie_agent.exec.plugin import ToolError, context

__all__ = ["AwsProfilesError", "render_config", "write_config"]

DEFAULT_REGION = "eu-west-1"
HEADER = "# Generated by Archie from plugins.aws.settings.profiles; changes are overwritten."

_PROFILE_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]*")


class AwsProfilesError(ToolError):
    """``plugins.aws.settings`` cannot be turned into a safe ``~/.aws/config``."""


def _single_line(value: Any, what: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise AwsProfilesError(f"{what} must be a non-empty string")
    if "\n" in value or "\r" in value:
        raise AwsProfilesError(f"{what} must be a single line")
    return value


def render_config(region: Any, profiles: Mapping[str, Any]) -> str:
    """Validate and render the config text (sorted by profile name)."""
    region = _single_line(region, "plugins.aws.settings.region")
    sections = []
    for name in sorted(profiles):
        if not isinstance(name, str) or not _PROFILE_RE.fullmatch(name):
            raise AwsProfilesError(
                f"invalid AWS profile name {name!r}: must match {_PROFILE_RE.pattern}"
            )
        arn = _single_line(profiles[name], f"role ARN for AWS profile {name!r}")
        sections.append(
            f"[profile {name}]\n"
            f"region = {region}\n"
            f"role_arn = {arn}\n"
            "credential_source = Environment\n"
        )
    return HEADER + "\n\n" + "\n".join(sections)


def _check_overwritable(target: Path) -> None:
    """Refuse to touch a host-mounted or hand-written ``~/.aws/config``."""
    if os.path.ismount(target.parent):
        raise AwsProfilesError(
            "~/.aws is mounted from the host; remove that mount or plugins.aws.settings.profiles"
        )
    if os.path.ismount(target):
        raise AwsProfilesError(
            "~/.aws/config is mounted from the host; "
            "remove that mount or plugins.aws.settings.profiles"
        )
    if not target.exists() and not target.is_symlink():
        return
    try:
        with open(target, encoding="utf-8", errors="replace") as fh:
            first = fh.readline()
    except OSError as exc:
        raise AwsProfilesError(
            f"~/.aws/config was not generated by Archie; refusing to overwrite it ({exc})"
        ) from exc
    if first.rstrip("\n") != HEADER:
        raise AwsProfilesError(
            "~/.aws/config was not generated by Archie; refusing to overwrite it"
        )


def _atomic_write(target: Path, text: str) -> None:
    directory = target.parent
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    os.chmod(directory, 0o700)
    fd, tmp = tempfile.mkstemp(dir=directory, prefix=".config.", suffix=".tmp")
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, target)
    except BaseException:
        try:
            os.unlink(tmp)
        except FileNotFoundError:
            pass
        raise


def write_config() -> Path | None:
    """Write ``~/.aws/config`` from the AWS plugin settings; None when no profiles."""
    settings = context().settings
    profiles = settings.get("profiles")
    if not profiles:
        return None
    if not isinstance(profiles, Mapping):
        raise AwsProfilesError("plugins.aws.settings.profiles must map profile name to role ARN")
    region = settings.get("region")
    text = render_config(DEFAULT_REGION if region is None else region, profiles)
    target = Path.home() / ".aws" / "config"
    _check_overwritable(target)
    _atomic_write(target, text)
    return target
