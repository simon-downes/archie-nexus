"""AWS startup hook: ``~/.aws/config`` generation rules (design "AWS plugin")."""

import os
import stat
from dataclasses import replace
from pathlib import Path

import pytest
from archie_agent.exec.plugin import CredentialSource, install_context
from archie_agent.exec.plugin_testing import make_plugin_context
from archie_plugins.aws import profiles as profiles_module
from archie_plugins.aws.profiles import (
    BASE_PROFILE,
    CREDENTIAL_PROCESS,
    AwsProfilesError,
    render_config,
    write_config,
)

PROFILES = {
    "agent-staging": "arn:aws:iam::111111111111:role/agent-access",
    "agent-production": "arn:aws:iam::222222222222:role/agent-access",
}

EXPECTED = f"""\
# Generated by Archie from plugins.aws.settings.profiles; changes are overwritten.

[profile archie-base]
region = eu-west-1
credential_process = {CREDENTIAL_PROCESS}

[profile agent-production]
region = eu-west-1
role_arn = arn:aws:iam::222222222222:role/agent-access
source_profile = archie-base

[profile agent-staging]
region = eu-west-1
role_arn = arn:aws:iam::111111111111:role/agent-access
source_profile = archie-base
"""

OLD = "[profile old]\nregion = us-east-1\n"
GENERATED_OLD = (
    "# Generated by Archie from plugins.aws.settings.profiles; changes are overwritten.\n"
    "\n[profile old]\nregion = us-east-1\n"
)


@pytest.fixture
def home(tmp_path, monkeypatch):
    home = tmp_path / "home"
    home.mkdir()
    monkeypatch.setenv("HOME", str(home))
    yield home
    install_context(None)


@pytest.fixture
def credential_calls():
    return []


@pytest.fixture
def use_settings(tmp_path, credential_calls):
    """Install an AWS context with ``settings``; record any credential read."""

    def install(settings):
        ctx = make_plugin_context("aws", tmp_path=tmp_path / "ctx", settings=settings)
        loader = lambda: credential_calls.append(1) or "secret"  # noqa: E731
        install_context(replace(ctx, credentials=CredentialSource("aws", loader=loader)))

    return install


def _config(home: Path) -> Path:
    return home / ".aws" / "config"


def _mode(path: Path) -> int:
    return stat.S_IMODE(path.stat().st_mode)


def _existing(home: Path, text: str = OLD) -> Path:
    target = _config(home)
    target.parent.mkdir(mode=0o700)
    target.write_text(text)
    return target


def test_sorted_deterministic_output(home, use_settings):
    use_settings({"profiles": PROFILES})
    assert write_config() == _config(home)
    first = _config(home).read_text()
    assert first == EXPECTED
    use_settings({"profiles": dict(reversed(PROFILES.items()))})
    write_config()
    assert _config(home).read_text() == first


def test_file_0600_and_dir_0700(home, use_settings):
    use_settings({"profiles": PROFILES})
    write_config()
    assert _mode(_config(home)) == 0o600
    assert _mode(_config(home).parent) == 0o700


def test_existing_dir_tightened(home, use_settings):
    (home / ".aws").mkdir()
    os.chmod(home / ".aws", 0o755)
    use_settings({"profiles": PROFILES})
    write_config()
    assert _mode(home / ".aws") == 0o700


def test_previously_generated_file_replaced(home, use_settings):
    target = _existing(home, GENERATED_OLD)
    os.chmod(target, 0o644)
    use_settings({"profiles": PROFILES})
    write_config()
    assert target.read_text() == EXPECTED
    assert _mode(target) == 0o600


@pytest.mark.parametrize(
    ("profiles", "needle"),
    [
        ({"bad name": "arn:aws:iam::1:role/r"}, "'bad name'"),
        ({"-leading": "arn:aws:iam::1:role/r"}, "'-leading'"),
        ({"x]\n[profile y": "arn:aws:iam::1:role/r"}, "profile name"),
        ({"ok": "arn:aws:iam::1:role/r\n[profile evil]"}, "'ok'"),
        ({"ok": "arn:aws:iam::1:role/r\rregion = x"}, "'ok'"),
        ({"ok": ""}, "'ok'"),
        ({"ok": "   "}, "'ok'"),
        ({"dev\n": "arn:aws:iam::1:role/r"}, "'dev\\n'"),
    ],
)
def test_invalid_profiles_rejected_and_file_kept(home, use_settings, profiles, needle):
    target = _existing(home)
    use_settings({"profiles": {**PROFILES, **profiles}})
    with pytest.raises(AwsProfilesError) as exc:
        write_config()
    assert needle in str(exc.value)
    assert target.read_text() == OLD
    assert sorted(p.name for p in target.parent.iterdir()) == ["config"]


@pytest.mark.parametrize("region", ["", "eu-west-1\n[profile x]", "eu\rwest"])
def test_invalid_region_rejected(home, use_settings, region):
    use_settings({"region": region, "profiles": PROFILES})
    with pytest.raises(AwsProfilesError, match="region"):
        write_config()
    assert not (home / ".aws").exists()


def test_validation_happens_before_touching_filesystem(home, use_settings):
    use_settings({"profiles": {"bad name": "arn"}})
    with pytest.raises(AwsProfilesError):
        write_config()
    assert not (home / ".aws").exists()


@pytest.mark.parametrize("profiles", [None, {}])
def test_no_profiles_creates_nothing(home, use_settings, profiles):
    use_settings({"profiles": profiles})
    assert write_config() is None
    assert not (home / ".aws").exists()


def test_no_profiles_leaves_existing_file(home, use_settings):
    target = _existing(home)
    os.chmod(target.parent, 0o755)
    use_settings({"profiles": None})
    assert write_config() is None
    assert target.read_text() == OLD
    assert _mode(target.parent) == 0o755


def test_failed_replace_keeps_old_file_and_removes_temp(home, use_settings, monkeypatch):
    target = _existing(home, GENERATED_OLD)

    def boom(src, dst):
        raise OSError("disk full")

    monkeypatch.setattr(profiles_module.os, "replace", boom)
    use_settings({"profiles": PROFILES})
    with pytest.raises(OSError, match="disk full"):
        write_config()
    assert target.read_text() == GENERATED_OLD
    assert sorted(p.name for p in target.parent.iterdir()) == ["config"]


def test_region_default_and_override(home, use_settings):
    use_settings({"profiles": {"a": "arn:aws:iam::1:role/r"}})
    write_config()
    assert "region = eu-west-1\n" in _config(home).read_text()
    use_settings({"region": "us-east-1", "profiles": {"a": "arn:aws:iam::1:role/r"}})
    write_config()
    text = _config(home).read_text()
    assert "region = us-east-1\n" in text
    assert "eu-west-1" not in text


def test_never_reads_credentials(home, use_settings, credential_calls):
    use_settings({"profiles": PROFILES})
    write_config()
    assert credential_calls == []
    text = _config(home).read_text()
    for needle in ("aws_access_key_id", "aws_secret_access_key", "aws_session_token", "secret"):
        assert needle not in text


@pytest.mark.parametrize(
    "existing",
    [OLD, "", "\n" + GENERATED_OLD, " " + GENERATED_OLD, GENERATED_OLD.replace("Archie", "Bob")],
)
def test_non_generated_file_left_byte_identical(home, use_settings, existing):
    target = _existing(home, existing)
    before = target.read_bytes()
    use_settings({"profiles": PROFILES})
    with pytest.raises(AwsProfilesError, match="not generated by Archie; refusing to overwrite"):
        write_config()
    assert target.read_bytes() == before
    assert sorted(p.name for p in target.parent.iterdir()) == ["config"]


@pytest.mark.parametrize(
    ("mounted", "needle"), [(".aws", "~/.aws is"), ("config", "~/.aws/config is")]
)
def test_host_mount_refused(home, use_settings, monkeypatch, mounted, needle):
    target = _existing(home, GENERATED_OLD)
    monkeypatch.setattr(profiles_module.os.path, "ismount", lambda p: Path(p).name == mounted)
    use_settings({"profiles": PROFILES})
    with pytest.raises(AwsProfilesError, match="mounted from the host") as exc:
        write_config()
    assert str(exc.value).startswith(needle)
    assert target.read_text() == GENERATED_OLD


def test_mount_check_skipped_without_profiles(home, use_settings, monkeypatch):
    monkeypatch.setattr(profiles_module.os.path, "ismount", lambda p: True)
    use_settings({"profiles": None})
    assert write_config() is None


def test_credential_process_script_ships_with_plugin():
    assert CREDENTIAL_PROCESS.name == "credential-process"
    assert CREDENTIAL_PROCESS.is_file()
    assert os.access(CREDENTIAL_PROCESS, os.X_OK)


def test_credential_process_path_is_shell_quoted():
    text = render_config("eu-west-1", {}, credential_process=Path("/opt/my plugins/cp"))
    assert "credential_process = '/opt/my plugins/cp'\n" in text


def test_base_profile_name_is_reserved(home, use_settings):
    use_settings({"profiles": {BASE_PROFILE: "arn:aws:iam::1:role/r"}})
    with pytest.raises(AwsProfilesError, match="reserved"):
        write_config()
